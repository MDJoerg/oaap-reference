"""The CLI reference, generated from the parser (RFC-0078 stage 0).

`oaap help` prints an overview; `oaap help --markdown DIR` writes one
Markdown file per command, with the front matter of RFC-0078 §4, into a
directory -- in the repositories that is `oaap-docs/cli/generated/`.

Nothing here describes a command by itself. Names, arguments and help
texts come from the argparse parser `appctl.py` runs; whether a command
needs root comes from the `is_read_only()` that refuses it. What argparse
cannot know -- the commands `bin/oaap` implements itself, and which
groups it passes on under their own name -- is handed in by the caller.

Standard library only; the node has no extra packages for this.
"""
import argparse
import datetime
import os
import re

# Every generated file carries this line; `write_markdown` removes a file
# with it that it did not write this time (a command renamed or retired),
# and never touches a file without it.
MARKER = "<!-- generated by `oaap help --markdown` -- do not edit, regenerate -->"

# RFC-0078 §5: the audience follows the command's gate. Only server_admin
# has a shell on the node; `support` is its read-only counterpart
# (oaap.core.identity, RFC-0039) and gets what runs without root.
AUDIENCE_ROOT = ["server_admin"]
AUDIENCE_READ = ["server_admin", "support"]

WIDTH = 78


class Command:
    def __init__(self, name, form, help_text, internal, parser, gates,
                 action_dest):
        self.name = name                # appctl.py's own name
        self.form = form                # how a person types it
        self.help = help_text
        self.internal = internal
        self.parser = parser
        self.gates = gates              # [(action or None, read_only)]
        self.action_dest = action_dest  # the positional the gates vary

    @property
    def id(self):
        return "cli/" + self.form[len("oaap "):].replace(" ", "/")

    @property
    def filename(self):
        return self.form[len("oaap "):].replace(" ", "-") + ".md"

    @property
    def root(self):
        """True: always sudo; False: never; None: depends on the action."""
        ro = {r for _a, r in self.gates}
        if ro == {True}:
            return False
        if ro == {False}:
            return True
        return None

    @property
    def audience(self):
        if self.internal or self.root is True:
            return AUDIENCE_ROOT
        return AUDIENCE_READ


def read_version(appctl_dir):
    """VERSION lies next to appctl.py on a node, one level up in the repo."""
    for cand in (os.path.join(appctl_dir, "VERSION"),
                 os.path.join(appctl_dir, "..", "VERSION")):
        try:
            with open(cand, encoding="utf-8") as f:
                v = f.read().strip()
            if v:
                return v
        except OSError:
            continue
    return "unknown"


def _subparsers(parser):
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            return a
    raise ValueError("parser has no subcommands")


def _gate_actions(sp):
    """The positional whose choices decide the gate: `action` (most
    commands) -- the one `is_read_only()` reads."""
    for a in sp._actions:
        if not a.option_strings and a.dest == "action" and a.choices:
            return a
    return None


def commands(parser, is_read_only, wrapper_groups):
    """Every subcommand of `parser`, in definition order, with the gate
    probed per action through the caller's own `is_read_only`."""
    sub = _subparsers(parser)
    helps = {c.dest: (c.help or "") for c in sub._choices_actions}
    out = []
    for name, sp in sub.choices.items():
        form = f"oaap {name}" if name in wrapper_groups else f"oaap app {name}"
        text = helps.get(name, "")
        internal = text.lower().startswith("internal")
        base = {a.dest: a.default for a in sp._actions
                if a.dest is not argparse.SUPPRESS and a.dest != "help"}
        base.setdefault("action", None)
        gate = _gate_actions(sp)
        gates = []
        for choice in (list(gate.choices) if gate else [None]):
            ns = argparse.Namespace(**dict(base, cmd=name))
            if gate:
                setattr(ns, gate.dest, choice)
            gates.append((choice, bool(is_read_only(ns))))
        out.append(Command(name, form, text, internal, sp, gates,
                           gate.dest if gate else None))
    return out


# --- formatting ------------------------------------------------------------

def _quiet(sp):
    # Python 3.14 colours argparse output; a file must not get escapes.
    if hasattr(sp, "color"):
        sp.color = False


USAGE_LINES = 4


def _usage(cmd):
    """argparse's own usage line when it is short; otherwise the
    positionals and `[options]` -- the table below names every option, and
    a usage of thirty lines (oaap tenant) helps nobody."""
    sp = cmd.parser
    _quiet(sp)
    old_prog, old_cols = sp.prog, os.environ.get("COLUMNS")
    sp.prog = cmd.form
    os.environ["COLUMNS"] = str(WIDTH)
    try:
        text = sp.format_usage()
    finally:
        sp.prog = old_prog
        if old_cols is None:
            os.environ.pop("COLUMNS", None)
        else:
            os.environ["COLUMNS"] = old_cols
    text = re.sub(r"^usage:\s*", "", text.strip()).replace(" [-h]", "", 1)
    if len(text.splitlines()) <= USAGE_LINES:
        return text
    parts = [cmd.form]
    for a in sp._actions:
        if a.option_strings:
            continue
        word = ("{" + ",".join(a.choices) + "}") if a.choices else (a.metavar or a.dest)
        parts.append(f"[{word}]" if a.nargs in ("?", "*") else word)
    if any(a.option_strings and not isinstance(a, argparse._HelpAction)
           for a in sp._actions):
        parts.append("[options]")
    return " ".join(parts)


def _expand(sp, action):
    if not action.help or action.help is argparse.SUPPRESS:
        return ""
    try:
        return sp._get_formatter()._expand_help(action)
    except Exception:
        return action.help


def _arg_name(a):
    if not a.option_strings:
        return a.metavar or a.dest
    names = ", ".join(a.option_strings)
    if a.nargs == 0:
        return names
    metavar = a.metavar or a.dest.upper()
    return f"{names} {metavar}"


def _cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def _arguments(cmd):
    rows = []
    for a in cmd.parser._actions:
        if isinstance(a, argparse._HelpAction):
            continue
        meaning = _cell(_expand(cmd.parser, a))
        if a.dest == cmd.action_dest and not meaning:
            meaning = "what to do -- see Actions below"
        extra = []
        if a.choices and a.dest != cmd.action_dest:
            extra.append("one of " + ", ".join(f"`{c}`" for c in a.choices))
        if a.option_strings and a.nargs != 0 and a.default not in (
                None, "", [], False, argparse.SUPPRESS) \
                and "default" not in meaning.lower():
            extra.append(f"default `{a.default}`")
        if isinstance(a, argparse._AppendAction) \
                and "repeatable" not in meaning.lower():
            extra.append("repeatable")
        if extra:
            meaning = (meaning + " " if meaning else "") + "(" + "; ".join(extra) + ")"
        rows.append((f"`{_arg_name(a)}`", meaning or "--"))
    return rows


def _root_line(cmd):
    if cmd.root is True:
        return "**Root:** needs `sudo`."
    if cmd.root is False:
        return "**Root:** runs without `sudo`."
    return "**Root:** depends on the action -- see the table below."


def _front_matter(doc_id, title, audience, version, today, tags):
    return "\n".join([
        "---",
        f"id: {doc_id}",
        f'title: "{title}"',
        f"audience: [{', '.join(audience)}]",
        f'checked_against: "{version}"',
        f"checked_on: {today}",
        "lang: en",
        f"tags: [{', '.join(tags)}]",
        "---",
        MARKER,
        "",
    ])


def command_markdown(cmd, version, today):
    group = cmd.form.split()[1]
    out = [_front_matter(cmd.id, cmd.form, cmd.audience, version, today,
                         ["cli", group] + (["internal"] if cmd.internal else []))]
    out.append(f"# `{cmd.form}`\n")
    if cmd.help:
        out.append(cmd.help.rstrip(".") + ".\n")
    if cmd.internal:
        out.append("Internal: called by the platform itself (update, "
                   "install, the portal or a timer). Not meant to be typed "
                   "by hand.\n")
    out.append(_root_line(cmd) + "\n")
    out.append("## Usage\n")
    out.append("```sh\n" + _usage(cmd) + "\n```\n")
    rows = _arguments(cmd)
    if rows:
        out.append("## Arguments\n")
        out.append("| Argument | Meaning |\n|---|---|")
        out.extend(f"| {n} | {m} |" for n, m in rows)
        out.append("")
    if cmd.action_dest:
        out.append("## Actions\n")
        out.append("Whether an action needs `sudo` is read from the rule the "
                   "node enforces, with the other arguments left out (e.g. "
                   "`node care` reads, `node care measure` needs `sudo`).\n")
        out.append("| Action | Needs `sudo` |\n|---|---|")
        out.extend(f"| `{a}` | {'no' if ro else 'yes'} |" for a, ro in cmd.gates)
        out.append("")
    out.append(f"Generated from the parser of reference {version}. Examples "
               "and the reasons behind a command: "
               "[hand-written CLI reference](../README.md).\n")
    return "\n".join(out)


def _sudo_cell(cmd):
    return {True: "yes", False: "no", None: "per action"}[cmd.root]


def index_markdown(cmds, version, today, wrapper_own):
    out = [_front_matter("cli/generated", "OAAP CLI reference (generated)",
                         AUDIENCE_READ, version, today, ["cli"])]
    out.append("# OAAP CLI reference (generated)\n")
    out.append(f"Every command of reference {version}, generated from the "
               "parser by `oaap help --markdown`. Examples, warnings and "
               "the reasons behind a command are in the "
               "[hand-written CLI reference](../README.md).\n")
    out.append("## Commands of the wrapper\n")
    out.append("| Command | Needs `sudo` | What it does |\n|---|---|---|")
    for _name, (usage, root, text) in wrapper_own.items():
        out.append(f"| `{usage}` | {'yes' if root else 'no'} | {_cell(text)} |")
    out.append("")
    for title, pick in (
            ("Node and tenant", lambda c: not c.internal
             and not c.form.startswith("oaap app ")),
            ("Instances and apps (`oaap app ...`)", lambda c: not c.internal
             and c.form.startswith("oaap app "))):
        out.append(f"## {title}\n")
        out.append("| Command | Needs `sudo` | What it does |\n|---|---|---|")
        for c in sorted(filter(pick, cmds), key=lambda c: c.form):
            out.append(f"| [`{c.form}`]({c.filename}) | {_sudo_cell(c)} | "
                       f"{_cell(c.help) or '--'} |")
        out.append("")
    out.append("## Internal\n")
    out.append("Called by update, install, the portal or a timer; listed so "
               "they can be recognised, not to be typed.\n")
    out.append("| Command | What it does |\n|---|---|")
    for c in sorted((c for c in cmds if c.internal), key=lambda c: c.form):
        text = re.sub(r"^internal:\s*", "", c.help, flags=re.I)
        out.append(f"| [`{c.form}`]({c.filename}) | {_cell(text)} |")
    out.append("")
    return "\n".join(out)


def write_markdown(directory, cmds, version, wrapper_own, today=None):
    today = today or datetime.date.today().isoformat()
    os.makedirs(directory, exist_ok=True)
    files = {"README.md": index_markdown(cmds, version, today, wrapper_own)}
    for c in cmds:
        files[c.filename] = command_markdown(c, version, today)
    for name in os.listdir(directory):
        path = os.path.join(directory, name)
        if name in files or not name.endswith(".md") or not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as f:
            generated = MARKER in f.read()
        if generated:
            os.remove(path)
    for name, text in files.items():
        with open(os.path.join(directory, name), "w", encoding="utf-8",
                  newline="\n") as f:
            f.write(text)
    return sorted(files)


def overview_text(cmds, version, wrapper_own):
    lines = [f"OAAP CLI, reference {version}  (* = needs sudo, "
             "~ = depends on the action)", ""]

    def row(form, mark, text):
        left = f"  {mark} {form}"
        text = " ".join(text.split())
        room = WIDTH - 34
        if len(text) > room:
            text = text[:room - 3].rstrip() + "..."
        lines.append(f"{left:<34}{text}" if len(left) < 34 else f"{left}  {text}")

    for _n, (usage, root, text) in wrapper_own.items():
        row(usage.replace("sudo ", "").split(" [")[0], "*" if root else " ", text)
    mark = {True: "*", False: " ", None: "~"}
    for c in cmds:
        if not c.internal:
            row(c.form, mark[c.root], c.help)
    lines += ["", "Details: <command> --help; the full reference: "
              "oaap help --markdown DIR", ""]
    return "\n".join(lines)
